  startDemoSimulation() {
    if (this.trackingState.timerId) {
      clearInterval(this.trackingState.timerId);
    }

    const intervalMs = Math.max(800, Math.round(3500 / this.trackingState.speedMultiplier));
    this.trackingState.timerId = setInterval(() => {
      this.advanceSimulationStep();
    }, intervalMs);
  }

  advanceSimulationStep() {
    if (this.trackingState.isLocationPaused) {
      // Driver has paused location sharing: car stays still, but status persists
      return;
    }

    this.trackingState.currentWaypointIndex += 1;

    // Check if reached destination
    if (this.trackingState.currentWaypointIndex >= PUNE_MUMBAI_CORRIDOR.length - 1) {
      this.trackingState.currentWaypointIndex = PUNE_MUMBAI_CORRIDOR.length - 1;
      const finalWp = PUNE_MUMBAI_CORRIDOR[this.trackingState.currentWaypointIndex];
      this.updateTrackingTelemetry(finalWp, true);
      this.handleTripArrived();
      return;
    }

    const nextWp = PUNE_MUMBAI_CORRIDOR[this.trackingState.currentWaypointIndex];
    this.updateTrackingTelemetry(nextWp, true);
  }

  updateTrackingTelemetry(waypoint, isAdvance = false) {
    if (!waypoint) return;

    // 1. Landmark & Destination
    const landmarkEl = document.getElementById('trackCurrentLandmark');
    if (landmarkEl) landmarkEl.textContent = waypoint.landmark;

    // 2. ETA Display
    const etaValEl = document.getElementById('trackEtaValue');
    const etaTimeEl = document.getElementById('trackEtaTime');
    if (etaValEl) {
      const minutesRemaining = Math.round(waypoint.etaMinutes / this.trackingState.speedMultiplier);
      const hours = Math.floor(minutesRemaining / 60);
      const mins = minutesRemaining % 60;
      etaValEl.textContent = hours > 0 ? `${hours}h ${mins}m` : `${mins}m`;
    }
    if (etaTimeEl) {
      const arrival = new Date(Date.now() + (waypoint.etaMinutes * 60 * 1000));
      etaTimeEl.textContent = `By ${arrival.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}`;
    }

    // 3. Distance Remaining & Speed
    const distValEl = document.getElementById('trackDistValue');
    if (distValEl) distValEl.textContent = waypoint.distanceRemainingKm;

    const speedValEl = document.getElementById('trackSpeedValue');
    if (speedValEl) {
      this.trackingState.currentSpeedKmh = Math.round(waypoint.speedKmh * this.trackingState.speedMultiplier);
      speedValEl.textContent = `Speed: ~${this.trackingState.currentSpeedKmh} km/h`;
    }

    // 4. Progress Bar Calculation
    const totalDist = 152;
    const coveredDist = totalDist - waypoint.distanceRemainingKm;
    const progressPct = Math.min(100, Math.max(0, Math.round((coveredDist / totalDist) * 100)));
    
    const progressBar = document.getElementById('trackProgressBar');
    if (progressBar) progressBar.style.width = `${progressPct}%`;

    const progressText = document.getElementById('trackProgressPercent');
    if (progressText) progressText.textContent = `${progressPct}% Completed`;

    // 5. Update Map Position & Smooth Heading Rotation
    if (this.trackingState.carMarker) {
      this.trackingState.carMarker.setLatLng([waypoint.lat, waypoint.lng]);

      // Calculate bearing angle to next waypoint for realistic car heading
      if (this.trackingState.currentWaypointIndex < PUNE_MUMBAI_CORRIDOR.length - 1) {
        const nextCoord = PUNE_MUMBAI_CORRIDOR[this.trackingState.currentWaypointIndex + 1];
        const heading = this.calculateBearing(waypoint.lat, waypoint.lng, nextCoord.lat, nextCoord.lng);
        const carIconEl = document.getElementById('driverCarIconElement');
        if (carIconEl) {
          carIconEl.style.transform = `rotate(${Math.round(heading)}deg)`;
        }
      }

      // Smooth pan map along journey
      if (isAdvance && this.trackingState.map && this.trackingState.role === 'passenger') {
        this.trackingState.map.panTo([waypoint.lat, waypoint.lng], { animate: true, duration: 1.2 });
      }
    }

    // 6. Broadcast via Socket.IO if in Driver role and connected
    if (this.trackingState.socket && this.trackingState.role === 'driver') {
      this.trackingState.socket.emit('driver:locationUpdate', {
        tripId: this.trackingState.activeTrip?.id,
        lat: waypoint.lat,
        lng: waypoint.lng,
        speed: this.trackingState.currentSpeedKmh,
        heading: 0,
        distanceRemainingKm: waypoint.distanceRemainingKm,
        etaMinutes: waypoint.etaMinutes,
        landmark: waypoint.landmark
      });
    }

    // 7. Sync with Firebase Adapter if available
    if (window.SaarthiFirebaseAdapter && typeof window.SaarthiFirebaseAdapter.syncTripLocation === 'function') {
      window.SaarthiFirebaseAdapter.syncTripLocation(this.trackingState.activeTrip?.id, {
        lat: waypoint.lat,
        lng: waypoint.lng,
        heading: 0,
        speed: this.trackingState.currentSpeedKmh,
        distanceRemainingKm: waypoint.distanceRemainingKm,
        etaMinutes: waypoint.etaMinutes,
        landmark: waypoint.landmark,
        isLocationPaused: this.trackingState.isLocationPaused
      });
    }
  }

  calculateBearing(lat1, lon1, lat2, lon2) {
    const toRad = deg => (deg * Math.PI) / 180;
    const toDeg = rad => (rad * 180) / Math.PI;
    const dLon = toRad(lon2 - lon1);
    const y = Math.sin(dLon) * Math.cos(toRad(lat2));
    const x = Math.cos(toRad(lat1)) * Math.sin(toRad(lat2)) - Math.sin(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.cos(dLon);
    return (toDeg(Math.atan2(y, x)) + 360) % 360;
  }

