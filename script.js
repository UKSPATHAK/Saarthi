  handleGlobalSearch(query) {
    const raw = (query || '').trim();
    if (!raw) return;

    let fromVal = '';
    let toVal = '';

    const separators = [' to ', ' -> ', ' - ', ' → '];
    let matchedSep = separators.find(s => raw.toLowerCase().includes(s));

    if (matchedSep) {
      const parts = raw.split(new RegExp(matchedSep, 'i'));
      fromVal = parts[0]?.trim() || '';
      toVal = parts[1]?.trim() || '';
    } else {
      fromVal = raw;
    }

    const searchFromInput = document.getElementById('searchFrom');
    const searchToInput = document.getElementById('searchTo');

    if (searchFromInput && fromVal) {
      searchFromInput.value = fromVal;
      this.searchQuery.from = fromVal;
      this.updateClearBtnVisibility('searchFrom');
    }
    if (searchToInput && toVal) {
      searchToInput.value = toVal;
      this.searchQuery.to = toVal;
      this.updateClearBtnVisibility('searchTo');
    }

    this.searchRides();
    this.navigateToSection('resultsSection');
  }

