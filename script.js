  bookSeat(ride) {
    if (!this.requireAuth(() => this.bookSeat(ride), this.t('authRequiredBooking'))) {
      return;
    }

    if (ride.seats <= 0) {
      alert(this.t('noRidesFoundTitle'));
      return;
    }

    ride.seats -= 1;
    this.saveRides();

    const bookingRef = `BK-${Math.floor(1000 + Math.random() * 9000)}`;
    const newBooking = {
      id: bookingRef,
      rideId: ride.id,
      from: ride.from,
      to: ride.to,
      pickup: ride.pickup,
      drop: ride.drop,
      date: ride.date,
      time: ride.time,
      driver: ride.driver,
      driverRating: ride.rating,
      price: ride.price,
      seatsBooked: 1,
      vehicle: ride.vehicle,
      vehicleModel: ride.vehicleModel,
      status: "upcoming",
      bookedAt: new Date().toISOString()
    };

    this.bookings.unshift(newBooking);
    this.saveBookings();

    this.impactStats.sharedRides += 1;
    if (ride.vehicle === 'EV') {
      this.impactStats.evRides += 1;
      this.impactStats.co2eAvoidedKg += Math.round(ride.co2eSavedKg || 3.8);
    }
    this.impactStats.sharedDistanceKm += (ride.distanceKm || 150);
    this.impactStats.vehicleBreakdown[ride.vehicle] = (this.impactStats.vehicleBreakdown[ride.vehicle] || 0) + 1;
    this.saveImpactStats();

    const detailsModal = document.getElementById('rideDetailsModal');
    if (detailsModal) detailsModal.classList.add('hidden');

    this.renderRides();
    this.renderMyTrips();
    this.renderImpactStats();

    this.openBookingSuccessModal(newBooking);
    this.showToast(this.t('bookingSuccessTitle'), 'success');
  }

