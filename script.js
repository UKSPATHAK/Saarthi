  // ===========================================================================
  // 4. SMART RIDE MATCHING & RANKING ENGINE (Locality + City Canonical Match)
  // ===========================================================================
  calculateRideScore(ride) {
    let routeScore = 0;
    const fromInfo = this.getRouteCanonicalInfo(this.searchQuery.from);
    const toInfo = this.getRouteCanonicalInfo(this.searchQuery.to);
    const rFrom = ride.from.toLowerCase();
    const rTo = ride.to.toLowerCase();
    const rPickup = (ride.pickup || '').toLowerCase();
    const rDrop = (ride.drop || '').toLowerCase();

    let fromMatch = false;
    let toMatch = false;
    let localityBonus = 0;

    if (fromInfo.city || fromInfo.raw) {
      if (fromInfo.city && (rFrom.includes(fromInfo.city) || fromInfo.city.includes(rFrom))) {
        fromMatch = true;
      } else if (fromInfo.raw && (rFrom.includes(fromInfo.raw) || rPickup.includes(fromInfo.raw))) {
        fromMatch = true;
      }
      if (fromInfo.locality && (rPickup.includes(fromInfo.locality) || rFrom.includes(fromInfo.locality))) {
        fromMatch = true;
        localityBonus += 15; // Pickup landmark bonus
      }
    } else {
      fromMatch = true;
    }

    if (toInfo.city || toInfo.raw) {
      if (toInfo.city && (rTo.includes(toInfo.city) || toInfo.city.includes(rTo))) {
        toMatch = true;
      } else if (toInfo.raw && (rTo.includes(toInfo.raw) || rDrop.includes(toInfo.raw))) {
        toMatch = true;
      }
      if (toInfo.locality && (rDrop.includes(toInfo.locality) || rTo.includes(toInfo.locality))) {
        toMatch = true;
        localityBonus += 15; // Drop landmark bonus
      }
    } else {
      toMatch = true;
    }

    if (fromMatch && toMatch) {
      routeScore = 100 + localityBonus;
    } else if (fromMatch || toMatch) {
      routeScore = 50 + localityBonus;
    } else {
      routeScore = 10;
    }

    let timeScore = 80;

    let sustainabilityScore = 0;
    if (ride.vehicle === 'EV') {
      sustainabilityScore = 100;
    } else if (ride.vehicle === 'Hybrid') {
      sustainabilityScore = 75;
    } else if (ride.vehicle === 'CNG') {
      sustainabilityScore = 50;
    } else {
      sustainabilityScore = 20;
    }

    const ratingScore = (ride.rating / 5.0) * 100;
    const priceScore = Math.max(0, 100 - ((ride.price / 1200) * 100));

    let wRoute = 0.40;
    let wTime = 0.25;
    let wSust = 0.20;
    let wRate = 0.10;
    let wPrice = 0.05;

    if (this.evPreference) {
      wSust = 0.45;
      wRoute = 0.30;
      wTime = 0.15;
      wRate = 0.07;
      wPrice = 0.03;
    }

    return (routeScore * wRoute) +
           (timeScore * wTime) +
           (sustainabilityScore * wSust) +
           (ratingScore * wRate) +
           (priceScore * wPrice);
  }

  getFilteredAndSortedRides() {
    let result = [...this.rides];

    const fromInfo = this.getRouteCanonicalInfo(this.searchQuery.from);
    const toInfo = this.getRouteCanonicalInfo(this.searchQuery.to);

    if (fromInfo.city || fromInfo.locality || fromInfo.raw) {
      result = result.filter(r => {
        const rFrom = r.from.toLowerCase();
        const rPickup = (r.pickup || '').toLowerCase();
        const cityMatch = fromInfo.city && (rFrom.includes(fromInfo.city) || fromInfo.city.includes(rFrom));
        const rawMatch = fromInfo.raw && (rFrom.includes(fromInfo.raw) || rPickup.includes(fromInfo.raw));
        const locMatch = fromInfo.locality && (rPickup.includes(fromInfo.locality) || rFrom.includes(fromInfo.locality));
        return cityMatch || rawMatch || locMatch;
      });
    }

    if (toInfo.city || toInfo.locality || toInfo.raw) {
      result = result.filter(r => {
        const rTo = r.to.toLowerCase();
        const rDrop = (r.drop || '').toLowerCase();
        const cityMatch = toInfo.city && (rTo.includes(toInfo.city) || toInfo.city.includes(rTo));
        const rawMatch = toInfo.raw && (rTo.includes(toInfo.raw) || rDrop.includes(toInfo.raw));
        const locMatch = toInfo.locality && (rDrop.includes(toInfo.locality) || rTo.includes(toInfo.locality));
        return cityMatch || rawMatch || locMatch;
      });
    }

    if (this.searchQuery.passengers) {
      result = result.filter(r => r.seats >= this.searchQuery.passengers);
    }

    if (this.activeFilters.vehicleTypes.length > 0) {
      result = result.filter(r => this.activeFilters.vehicleTypes.includes(r.vehicle));
    } else {
      return [];
    }

    if (this.activeFilters.departureTimes.length > 0) {
      result = result.filter(r => this.activeFilters.departureTimes.includes(r.departurePeriod));
    }

    result = result.filter(r => r.price <= this.activeFilters.maxPrice);

    if (this.activeFilters.minRating > 0) {
      result = result.filter(r => r.rating >= this.activeFilters.minRating);
    }

    const sortBy = this.activeFilters.sortBy;
    if (sortBy === 'evs_first') {
      result.sort((a, b) => {
        const order = { 'EV': 1, 'Hybrid': 2, 'CNG': 3, 'Petrol': 4, 'Diesel': 5 };
        return (order[a.vehicle] || 99) - (order[b.vehicle] || 99);
      });
    } else if (sortBy === 'price_asc') {
      result.sort((a, b) => a.price - b.price);
    } else if (sortBy === 'departure_earliest') {
      result.sort((a, b) => a.time.localeCompare(b.time));
    } else if (sortBy === 'rating_highest') {
      result.sort((a, b) => b.rating - a.rating);
    } else {
      result.sort((a, b) => this.calculateRideScore(b) - this.calculateRideScore(a));
    }

    return result;
  }

