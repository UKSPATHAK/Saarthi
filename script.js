    // Store ONLY name and formatted size for UI preview (NO RAW SCAN OR DATA STORED)
    this.signupState.selectedFileName = file.name;
    this.signupState.selectedFileSize = (file.size / (1024 * 1024)).toFixed(2) + " MB";

