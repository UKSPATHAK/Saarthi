  handlePostRide() {
    const from = document.getElementById('offerFrom').value.trim();
    const to = document.getElementById('offerTo').value.trim();
    const date = document.getElementById('offerDate').value;
    const time = document.getElementById('offerTime').value;
    const vehicleType = document.getElementById('offerVehicleType').value;
    const vehicleModel = document.getElementById('offerVehicleModel').value.trim();
    const seats = parseInt(document.getElementById('offerSeats').value, 10);
    const price = parseInt(document.getElementById('offerPrice').value, 10);
    const pickup = document.getElementById('offerPickup').value.trim();
    const drop = document.getElementById('offerDrop').value.trim();
    const dashcamEquipped = Boolean(document.getElementById('offerDashcamEquipped')?.checked);

    if (!from || !to || !date || !time || !vehicleModel || !price || !pickup || !drop) {
      alert("Please fill in all the required ride details.");
      return;
    }

    let period = "morning";
    const hour = parseInt(time.split(':')[0], 10);
    if (hour >= 12 && hour < 17) period = "afternoon";
    else if (hour >= 17) period = "evening";

    const newRide = {
      id: Date.now(),
      driver: this.userProfile.name,
      avatar: "https://images.unsplash.com/photo-1535713875002-d1d0cf377fde?w=120&auto=format&fit=crop&q=80",
      from: from,
      to: to,
      date: date,
      time: time,
      departurePeriod: period,
      price: price,
      seats: seats,
      vehicle: vehicleType,
      vehicleModel: vehicleModel,
      rating: 4.9,
      verified: true,
      dashcam: dashcamEquipped,
      completedTrips: this.userProfile.tripsCompleted,
      pickup: pickup,
      drop: drop,
      amenities: ["AC", "Luggage", "Music", "No Smoking"],
      distanceKm: 160,
      co2eSavedKg: vehicleType === 'EV' ? 4.0 : 1.5,
      community: "Community Ride"
    };

    this.rides.unshift(newRide);
    this.saveRides();

    document.getElementById('offerRideForm').reset();
    const dashcamCb = document.getElementById('offerDashcamEquipped');
    if (dashcamCb) dashcamCb.checked = true;

    this.showToast(this.t('postSuccessTitle'), 'success');
    this.renderRides();
    this.navigateToSection('resultsSection');
  }

