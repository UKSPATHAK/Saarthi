  // Helper to extract canonical city and locality for matching
  getRouteCanonicalInfo(input) {
    if (!input || !input.trim()) return { city: '', locality: '', raw: '' };
    const raw = input.trim();
    const provider = window.SaarthiLocations && window.SaarthiLocations.Provider;
    let city = provider ? provider.resolveCanonicalCity(raw) : raw;
    let locality = '';
    if (raw.includes(',')) {
      const parts = raw.split(',').map(s => s.trim());
      locality = parts[0];
      if (parts[1]) {
        city = provider ? provider.resolveCanonicalCity(parts[1]) : parts[1];
      }
    } else {
      if (provider) {
        const canonical = provider.resolveCanonicalCity(raw);
        if (canonical.toLowerCase() !== raw.toLowerCase()) {
          city = canonical;
          locality = raw;
        }
      }
    }
    return { city: city.toLowerCase(), locality: locality.toLowerCase(), raw: raw.toLowerCase() };
  }

